CREATE TABLE IF NOT EXISTS classbook_policies (
 subject_id INT UNSIGNED PRIMARY KEY,
 lecture_percent DECIMAL(5,2) NOT NULL DEFAULT 65,
 midterm_percent DECIMAL(5,2) NOT NULL DEFAULT 50,
 passing_percent DECIMAL(5,2) NOT NULL DEFAULT 75,
 policy_label VARCHAR(150) NOT NULL DEFAULT 'Provisional defaults',
 conversion_json TEXT NULL,
 FOREIGN KEY(subject_id) REFERENCES subjects(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS classbook_account_meta (
 role VARCHAR(20) NOT NULL, account_id INT UNSIGNED NOT NULL,
 revision INT UNSIGNED NOT NULL DEFAULT 1,
 PRIMARY KEY(role,account_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS classbook_login_limits (
 bucket CHAR(64) PRIMARY KEY, attempts INT UNSIGNED NOT NULL DEFAULT 0,
 window_started DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS classbook_migrations (
 version INT PRIMARY KEY, applied_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
