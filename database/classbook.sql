-- Additive classroom-record migration. Existing percentage grades are preserved.
CREATE TABLE IF NOT EXISTS classbook_admins (
 id INT UNSIGNED PRIMARY KEY AUTO_INCREMENT, username VARCHAR(80) NOT NULL UNIQUE,
 full_name VARCHAR(150) NOT NULL, password_hash VARCHAR(255) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS classbook_access (
 role VARCHAR(20) NOT NULL, account_id INT UNSIGNED NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'active', PRIMARY KEY(role,account_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS classbook_tokens (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT, role VARCHAR(20) NOT NULL,
 account_id INT UNSIGNED NOT NULL, token_hash CHAR(64) NOT NULL UNIQUE,
 expires_at DATETIME NOT NULL, used_at DATETIME NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS classbook_settings (
 subject_id INT UNSIGNED PRIMARY KEY, revision INT UNSIGNED NOT NULL DEFAULT 1,
 state VARCHAR(20) NOT NULL DEFAULT 'draft', archived TINYINT NOT NULL DEFAULT 0,
 late_points DECIMAL(8,2) NOT NULL DEFAULT 3, absent_points DECIMAL(8,2) NOT NULL DEFAULT 0,
 excused_mode VARCHAR(20) NOT NULL DEFAULT 'makeup',
 online_full_minutes DECIMAL(10,2) NULL, online_partial_minutes DECIMAL(10,2) NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(subject_id) REFERENCES subjects(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS classbook_members (
 enrollment_id INT UNSIGNED PRIMARY KEY, status VARCHAR(20) NOT NULL DEFAULT 'active',
 starts_on DATE NOT NULL, reason VARCHAR(500) NOT NULL DEFAULT '',
 FOREIGN KEY(enrollment_id) REFERENCES enrollments(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS classbook_criteria (
 id INT UNSIGNED PRIMARY KEY AUTO_INCREMENT, subject_id INT UNSIGNED NOT NULL,
 group_key VARCHAR(20) NOT NULL, name VARCHAR(100) NOT NULL,
 kind VARCHAR(20) NOT NULL, weight DECIMAL(7,2) NOT NULL,
 aggregation VARCHAR(20) NOT NULL DEFAULT 'pooled',
 excused_mode VARCHAR(20) NOT NULL DEFAULT 'makeup',
 UNIQUE KEY criterion_name(subject_id,group_key,name),
 FOREIGN KEY(subject_id) REFERENCES subjects(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS classbook_activities (
 id INT UNSIGNED PRIMARY KEY AUTO_INCREMENT, criterion_id INT UNSIGNED NOT NULL,
 title VARCHAR(150) NOT NULL, maximum DECIMAL(12,2) NOT NULL, due_on DATE NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(criterion_id) REFERENCES classbook_criteria(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS classbook_scores (
 activity_id INT UNSIGNED NOT NULL, enrollment_id INT UNSIGNED NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'not_graded', earned DECIMAL(12,2) NULL,
 PRIMARY KEY(activity_id,enrollment_id),
 FOREIGN KEY(activity_id) REFERENCES classbook_activities(id) ON DELETE RESTRICT,
 FOREIGN KEY(enrollment_id) REFERENCES enrollments(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS classbook_meetings (
 id INT UNSIGNED PRIMARY KEY AUTO_INCREMENT, criterion_id INT UNSIGNED NOT NULL,
 meeting_date DATE NOT NULL, title VARCHAR(150) NOT NULL,
 source_key CHAR(64) NULL UNIQUE, source_json LONGTEXT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(criterion_id) REFERENCES classbook_criteria(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS classbook_attendance (
 meeting_id INT UNSIGNED NOT NULL, enrollment_id INT UNSIGNED NOT NULL,
 status VARCHAR(20) NOT NULL, duration_seconds DECIMAL(12,2) NULL,
 source_identity VARCHAR(255) NULL,
 PRIMARY KEY(meeting_id,enrollment_id),
 FOREIGN KEY(meeting_id) REFERENCES classbook_meetings(id) ON DELETE RESTRICT,
 FOREIGN KEY(enrollment_id) REFERENCES enrollments(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS classbook_imports (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT, subject_id INT UNSIGNED NOT NULL,
 fingerprint CHAR(64) NOT NULL, meeting_id INT UNSIGNED NOT NULL,
 actor_id INT UNSIGNED NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY once_per_class(subject_id,fingerprint),
 FOREIGN KEY(subject_id) REFERENCES subjects(id) ON DELETE RESTRICT,
 FOREIGN KEY(meeting_id) REFERENCES classbook_meetings(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS classbook_releases (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT, subject_id INT UNSIGNED NOT NULL,
 revision INT UNSIGNED NOT NULL, snapshot_json LONGTEXT NOT NULL,
 actor_id INT UNSIGNED NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(subject_id) REFERENCES subjects(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS classbook_audit (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT, actor_role VARCHAR(20) NOT NULL,
 actor_id INT UNSIGNED NOT NULL, subject_id INT UNSIGNED NULL,
 action VARCHAR(80) NOT NULL, detail_json LONGTEXT NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
